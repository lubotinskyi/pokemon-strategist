"""State графа Pokémon Team Strategist.

Описывает все данные, которые путешествуют между узлами.
"""

from typing import TypedDict


class TeamState(TypedDict, total=False):
    """Состояние обработки одной команды покемонов.

    total=False означает, что не все поля обязаны быть заполнены
    с самого начала — они появляются по мере прохождения узлов.
    """

    # ── Вход ────────────────────────────────────────────────
    selected: list[str]        # выбранные покемоны, например ["pikachu", "charizard"]
    opponent: list[str]        # предполагаемый противник, например ["mewtwo"]

    # ── Данные из PokéAPI ───────────────────────────────────
    pokemon_data: dict         # {имя: {"types": [...], "stats": {...}, ...}}

    # ── Анализ слабостей ────────────────────────────────────
    weaknesses: dict           # {тип: сколько покемонов уязвимы}
    analysis: str              # текстовое описание слабостей

    # ── Предложение замены ──────────────────────────────────
    proposed: dict | None      # {"out": имя, "in": имя, "reason": текст}

    # ── Управление циклом ───────────────────────────────────
    attempts: int              # сколько попыток уже сделано
    max_attempts: int          # максимум попыток (например, 3)

    # ── Результат ───────────────────────────────────────────
    improved: bool             # стало ли лучше после замены
    final_team: list[str]      # итоговая команда
    sources: list[str]         # ссылки на PokéAPI для отчёта
    error: str | None          # текст ошибки, если что-то пошло не так